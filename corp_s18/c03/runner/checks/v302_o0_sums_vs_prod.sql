SELECT COALESCE(P.D, O.D) AS DL_DATA_DT, P.V AS VALUE_PROD, O.V AS VALUE_O0, P.Q AS QTY_PROD, O.Q AS QTY_O0
     , CASE WHEN P.V = O.V AND P.Q = O.Q THEN 'same' ELSE 'DIFF' END AS VERDICT
FROM (
    SELECT DL_DATA_DT AS D, SUM(`VALUE`) AS V, SUM(QTY) AS Q
    FROM `${hivevar:environment}_OUTBOUND_RDXDST_DB`.RDXTGT_RDXUNIT_STOCK_DLY
    WHERE DL_DATA_DT BETWEEN '${hivevar:from_dt}' AND '${hivevar:to_dt}'
    GROUP BY DL_DATA_DT
) P
FULL OUTER JOIN (
    SELECT DL_DATA_DT AS D, SUM(`VALUE`) AS V, SUM(QTY) AS Q
    FROM `${hivevar:tmp_db}`.`${hivevar:prefix}OUT_O0`
    GROUP BY DL_DATA_DT
) O
    ON P.D = O.D
ORDER BY DL_DATA_DT;
