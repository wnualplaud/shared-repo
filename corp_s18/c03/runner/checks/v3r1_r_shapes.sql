SELECT O, N_ROWS, N_ITEM_RDXCUST, N_ITEMS FROM (
SELECT 'or1' AS O, COUNT(*) AS N_ROWS, COUNT(DISTINCT SRC_RDXSRC_COLL_ITEM_ID, RDXCUST_NO) AS N_ITEM_RDXCUST, COUNT(DISTINCT SRC_RDXSRC_COLL_ITEM_ID) AS N_ITEMS
FROM `${hivevar:tmp_db}`.`${hivevar:prefix}OUT_OR1`
UNION ALL
SELECT 'or2' AS O, COUNT(*) AS N_ROWS, COUNT(DISTINCT SRC_RDXSRC_COLL_ITEM_ID, RDXCUST_NO) AS N_ITEM_RDXCUST, COUNT(DISTINCT SRC_RDXSRC_COLL_ITEM_ID) AS N_ITEMS
FROM `${hivevar:tmp_db}`.`${hivevar:prefix}OUT_OR2`
) X
ORDER BY O;
