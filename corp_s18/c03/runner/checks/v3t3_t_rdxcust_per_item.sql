SELECT O, N_RDXCUST, COUNT(*) AS ITEMS, SUM(N_ROWS) AS ROWS_
FROM (
    SELECT 'ot1' AS O, SRC_RDXSRC_COLL_ITEM_ID AS ID, COUNT(DISTINCT RDXCUST_NO) AS N_RDXCUST, COUNT(*) AS N_ROWS
    FROM `${hivevar:tmp_db}`.`${hivevar:prefix}OUT_OT1` GROUP BY SRC_RDXSRC_COLL_ITEM_ID
    UNION ALL
    SELECT 'ot2' AS O, SRC_RDXSRC_COLL_ITEM_ID AS ID, COUNT(DISTINCT RDXCUST_NO) AS N_RDXCUST, COUNT(*) AS N_ROWS
    FROM `${hivevar:tmp_db}`.`${hivevar:prefix}OUT_OT2` GROUP BY SRC_RDXSRC_COLL_ITEM_ID
) X
GROUP BY O, N_RDXCUST
ORDER BY O, N_RDXCUST;
