SELECT SRC, N_RDXCUST, COUNT(*) AS COLLATERALS
FROM (
    SELECT 'p2 card' AS SRC, RDXSRC_CODE AS JOB, CMS_COLL_ID AS COLL, COUNT(DISTINCT RDXCUST_NO) AS N_RDXCUST
    FROM `${hivevar:tmp_db}`.`${hivevar:prefix}CARD` GROUP BY RDXSRC_CODE, CMS_COLL_ID
    UNION ALL
    SELECT 'p3 rdxset_t' AS SRC, RDXSRCT_CODE AS JOB, COLL AS COLL, COUNT(DISTINCT CUST_RDXCUST) AS N_RDXCUST
    FROM `${hivevar:tmp_db}`.`${hivevar:prefix}RDXSET_T` GROUP BY RDXSRCT_CODE, RDXSET_ID, COLL
) X
GROUP BY SRC, N_RDXCUST
ORDER BY SRC, N_RDXCUST;
