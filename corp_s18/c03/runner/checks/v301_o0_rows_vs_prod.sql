SELECT COALESCE(P.D, O.D) AS DL_DATA_DT, P.LOAD_DT, P.N AS N_PROD, O.N AS N_O0
     , CASE WHEN P.N = O.N THEN 'same' ELSE 'DIFF' END AS VERDICT
FROM (
    SELECT DL_DATA_DT AS D, COUNT(*) AS N, MAX(SUBSTR(CAST(DL_LOAD_TS AS STRING), 1, 10)) AS LOAD_DT
    FROM `${hivevar:environment}_OUTBOUND_RDXDST_DB`.RDXTGT_RDXUNIT_STOCK_DLY
    WHERE DL_DATA_DT BETWEEN '${hivevar:from_dt}' AND '${hivevar:to_dt}'
    GROUP BY DL_DATA_DT
) P
FULL OUTER JOIN (
    SELECT DL_DATA_DT AS D, COUNT(*) AS N
    FROM `${hivevar:tmp_db}`.`${hivevar:prefix}OUT_O0`
    GROUP BY DL_DATA_DT
) O
    ON P.D = O.D
ORDER BY DL_DATA_DT;
