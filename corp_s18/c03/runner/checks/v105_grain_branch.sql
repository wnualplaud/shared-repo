SELECT COUNT(*) AS N_ROWS
     , COUNT(DISTINCT BR_NO) AS N_BRANCHES
     , SUM(CASE WHEN RDXBANK_GRP_CODE IN ('RDX_GRP1', 'RDX_GRP2', 'RDX_GRP3', 'RDX_GRP4', 'RDX_GRP5', 'RDX_GRP6') THEN 1 ELSE 0 END) AS N_ROWS_RDXUNIT
     , COUNT(DISTINCT CASE WHEN RDXBANK_GRP_CODE IN ('RDX_GRP1', 'RDX_GRP2', 'RDX_GRP3', 'RDX_GRP4', 'RDX_GRP5', 'RDX_GRP6') THEN BR_NO END) AS N_BRANCHES_RDXUNIT
FROM `RDXDW${hivevar:dbdwenv}`.RDX_DIM1;
