SELECT KIND, FLAG, COUNT(*) AS ITEMS, SUM(IN_O0) AS IN_O0, SUM(IN_OT1) AS IN_OT1, SUM(IN_OT2) AS IN_OT2
FROM (
    SELECT CASE WHEN R.CODE IS NOT NULL THEN 'R' WHEN T.CODE IS NOT NULL THEN 'T' ELSE 'not in TFILE / RFILE' END AS KIND
         , I.SPC_SURPRISE_CHECK AS FLAG
     , CASE WHEN O0.ID IS NOT NULL THEN 1 ELSE 0 END AS IN_O0
     , CASE WHEN OT1.ID IS NOT NULL THEN 1 ELSE 0 END AS IN_OT1
     , CASE WHEN OT2.ID IS NOT NULL THEN 1 ELSE 0 END AS IN_OT2
    FROM `${hivevar:tmp_db}`.`${hivevar:prefix}STOCK_ITEM` I
    LEFT JOIN (SELECT DISTINCT TRIM(RDXSRCR_CODE) AS CODE FROM `${hivevar:environment}_PERSIST_RDXSRC_DB`.RDXSRC_TBL_RDXSRC_RDXSET_RFILE_INFO WHERE DL_DATA_DT = '${hivevar:dl_data_dt}') R
        ON I.RDXSRC_CODE = R.CODE
    LEFT JOIN (SELECT DISTINCT TRIM(RDXSRCT_CODE) AS CODE FROM `${hivevar:environment}_PERSIST_RDXSRC_DB`.RDXSRC_TBL_RDXSRC_RDXSET_TFILE_INFO WHERE DL_DATA_DT = '${hivevar:dl_data_dt}') T
        ON I.RDXSRC_CODE = T.CODE
    LEFT JOIN (SELECT DISTINCT SRC_COLL_SPC_NO AS ID FROM `${hivevar:tmp_db}`.`${hivevar:prefix}OUT_O0`) O0 ON I.COLL_SPC_NO = O0.ID
    LEFT JOIN (SELECT DISTINCT SRC_COLL_SPC_NO AS ID FROM `${hivevar:tmp_db}`.`${hivevar:prefix}OUT_OT1`) OT1 ON I.COLL_SPC_NO = OT1.ID
    LEFT JOIN (SELECT DISTINCT SRC_COLL_SPC_NO AS ID FROM `${hivevar:tmp_db}`.`${hivevar:prefix}OUT_OT2`) OT2 ON I.COLL_SPC_NO = OT2.ID
) X
GROUP BY KIND, FLAG
ORDER BY KIND, FLAG;
