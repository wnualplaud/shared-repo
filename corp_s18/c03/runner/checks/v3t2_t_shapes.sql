SELECT O, N_ROWS, N_ITEM_RDXCUST, N_ITEMS FROM (
SELECT 'o0' AS O, COUNT(*) AS N_ROWS, COUNT(DISTINCT SRC_COLL_SPC_NO, RDXCUST_NO) AS N_ITEM_RDXCUST, COUNT(DISTINCT SRC_COLL_SPC_NO) AS N_ITEMS
FROM `${hivevar:tmp_db}`.`${hivevar:prefix}OUT_O0`
UNION ALL
SELECT 'ot1' AS O, COUNT(*) AS N_ROWS, COUNT(DISTINCT SRC_COLL_SPC_NO, RDXCUST_NO) AS N_ITEM_RDXCUST, COUNT(DISTINCT SRC_COLL_SPC_NO) AS N_ITEMS
FROM `${hivevar:tmp_db}`.`${hivevar:prefix}OUT_OT1`
UNION ALL
SELECT 'ot2' AS O, COUNT(*) AS N_ROWS, COUNT(DISTINCT SRC_COLL_SPC_NO, RDXCUST_NO) AS N_ITEM_RDXCUST, COUNT(DISTINCT SRC_COLL_SPC_NO) AS N_ITEMS
FROM `${hivevar:tmp_db}`.`${hivevar:prefix}OUT_OT2`
) X
ORDER BY O;
