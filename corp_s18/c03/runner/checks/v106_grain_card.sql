SELECT COUNT(*) AS N_ROWS
     , COUNT(DISTINCT TRIM(RDXSRCT_CODE), TRIM(CAST(COLL_ID AS STRING)), TRIM(RDXCUST_NO)) AS N_KEYS
     , COUNT(DISTINCT TRIM(RDXSRCT_CODE), RDXSET_ID, TRIM(CAST(COLL_ID AS STRING)), TRIM(RDXCUST_NO)) AS N_KEYS_WITH_RDXSET
FROM `${hivevar:environment}_PERSIST_RDXSRC_DB`.RDXSRC_TBL_RDXSRC_RDXSET_IMP_SPC_CARD
WHERE DL_DATA_DT = '${hivevar:dl_data_dt}'
  AND COLL_ID IS NOT NULL AND TRIM(COLL_ID) <> '' AND LOWER(TRIM(COLL_ID)) <> 'null'
  AND RDXCUST_NO IS NOT NULL AND TRIM(RDXCUST_NO) <> '' AND LOWER(TRIM(RDXCUST_NO)) <> 'null';
