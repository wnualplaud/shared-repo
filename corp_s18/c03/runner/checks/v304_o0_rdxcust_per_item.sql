SELECT O, N_RDXCUST, COUNT(*) AS ITEMS, SUM(N_ROWS) AS ROWS_
FROM (
    SELECT 'o0' AS O, SRC_COLL_SPC_NO AS ID, COUNT(DISTINCT RDXCUST_NO) AS N_RDXCUST, COUNT(*) AS N_ROWS
    FROM `${hivevar:tmp_db}`.`${hivevar:prefix}OUT_O0` GROUP BY SRC_COLL_SPC_NO
) X
GROUP BY O, N_RDXCUST
ORDER BY O, N_RDXCUST;
