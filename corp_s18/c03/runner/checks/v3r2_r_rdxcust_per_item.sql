SELECT O, N_RDXCUST, COUNT(*) AS ITEMS, SUM(N_ROWS) AS ROWS_
FROM (
    SELECT 'or1' AS O, SRC_COLL_SPC_NO AS ID, COUNT(DISTINCT RDXCUST_NO) AS N_RDXCUST, COUNT(*) AS N_ROWS
    FROM `${hivevar:tmp_db}`.`${hivevar:prefix}OUT_OR1` GROUP BY SRC_COLL_SPC_NO
    UNION ALL
    SELECT 'or2' AS O, SRC_COLL_SPC_NO AS ID, COUNT(DISTINCT RDXCUST_NO) AS N_RDXCUST, COUNT(*) AS N_ROWS
    FROM `${hivevar:tmp_db}`.`${hivevar:prefix}OUT_OR2` GROUP BY SRC_COLL_SPC_NO
) X
GROUP BY O, N_RDXCUST
ORDER BY O, N_RDXCUST;
