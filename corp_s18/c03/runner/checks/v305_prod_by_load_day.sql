SELECT LOAD_DT, FLAG, COUNT(DISTINCT D) AS N_PARTITIONS, MIN(D) AS FIRST_DT, MAX(D) AS LAST_DT, COUNT(*) AS N_ROWS
     , SUM(CASE WHEN SRC_RDXSRC_CODE IS NULL THEN 1 ELSE 0 END) AS N_KEY_NULL
FROM (
    SELECT SUBSTR(CAST(DL_LOAD_TS AS STRING), 1, 10) AS LOAD_DT, SURPRISE_FLAG AS FLAG, DL_DATA_DT AS D, SRC_RDXSRC_CODE
    FROM `${hivevar:environment}_OUTBOUND_RDXDST_DB`.RDXTGT_RDXUNIT_STOCK_DLY
) X
GROUP BY LOAD_DT, FLAG
ORDER BY LOAD_DT, FLAG;
