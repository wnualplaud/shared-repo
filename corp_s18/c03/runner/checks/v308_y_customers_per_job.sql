SELECT SRC, N_RDXCUST, COUNT(*) AS JOBS
FROM (
    SELECT 'customer_info' AS SRC, TRIM(CU.RDXSRC_CODE) AS JOB, COUNT(DISTINCT TRIM(CU.RDXCUST_NO)) AS N_RDXCUST
    FROM `${hivevar:environment}_PERSIST_RDXSRC_DB`.RDXSRC_TBL_RDXSRC_CUSTOMER_INFO CU
    INNER JOIN (SELECT DISTINCT RDXSRC_CODE AS JOB FROM `${hivevar:tmp_db}`.`${hivevar:prefix}ITEM_TRACE` WHERE SPC_SURPRISE_CHECK = 'Y') Y
        ON TRIM(CU.RDXSRC_CODE) = Y.JOB
    WHERE CU.DL_DATA_DT = '${hivevar:dl_data_dt}'
    GROUP BY TRIM(CU.RDXSRC_CODE)

    UNION ALL

    SELECT 'rdxset_spc' AS SRC, TRIM(TF.RDXSRCT_CODE) AS JOB, COUNT(DISTINCT TRIM(RS.CUST_RDXCUST)) AS N_RDXCUST
    FROM `${hivevar:environment}_PERSIST_RDXSRC_DB`.RDXSRC_TBL_RDXSRC_RDXSET_TFILE_INFO TF
    INNER JOIN (SELECT DISTINCT RDXSRC_CODE AS JOB FROM `${hivevar:tmp_db}`.`${hivevar:prefix}ITEM_TRACE` WHERE SPC_SURPRISE_CHECK = 'Y') Y
        ON TRIM(TF.RDXSRCT_CODE) = Y.JOB
    INNER JOIN `${hivevar:environment}_PERSIST_RDXSRC_DB`.RDXSRC_TBL_RDXSRC_RDXSET_SPC RS
        ON TF.RDXSET_ID = RS.RDXSET_ID
       AND RS.DL_DATA_DT = '${hivevar:dl_data_dt}'
    WHERE TF.DL_DATA_DT = '${hivevar:dl_data_dt}'
    GROUP BY TRIM(TF.RDXSRCT_CODE)
) X
GROUP BY SRC, N_RDXCUST
ORDER BY SRC, N_RDXCUST;
