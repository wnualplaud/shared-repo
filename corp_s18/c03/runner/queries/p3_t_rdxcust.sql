SELECT DISTINCT

        TRIM(CARD.RDXSRCT_CODE)                                    AS RDXSRC_CODE
    ,   TRIM(CARD.RDXSRCT_CODE)                                    AS LINK_T_CODE
    ,   TRIM(CAST(CARD.COLL_ID AS STRING))                      AS CMS_COLL_ID
    ,   TRIM(CARD.RDXCUST_NO)                                       AS RDXCUST_NO
    ,   't'                                                     AS LINE

FROM `${hivevar:environment}_PERSIST_RDXSRC_DB`.RDXSRC_TBL_RDXSRC_RDXSET_TFILE_INFO TFILE

    INNER JOIN `${hivevar:environment}_PERSIST_RDXSRC_DB`.RDXSRC_TBL_RDXSRC_RDXSET_SPC RDXSET_SPC
        ON RDXSET_SPC.RDXSET_ID = TFILE.RDXSET_ID
       AND RDXSET_SPC.DL_DATA_DT = '${hivevar:snap_dt}'

    INNER JOIN `${hivevar:environment}_PERSIST_RDXSRC_DB`.RDXSRC_TBL_RDXSRC_RDXSET_IMP_SPC_CARD CARD
        ON TRIM(CARD.RDXSRCT_CODE) = TRIM(TFILE.RDXSRCT_CODE)
       AND CARD.RDXSET_ID = RDXSET_SPC.RDXSET_ID
       AND TRIM(CAST(CARD.COLL_ID AS STRING)) = TRIM(CAST(RDXSET_SPC.COLL AS STRING))
       AND TRIM(CARD.RDXCUST_NO) = TRIM(RDXSET_SPC.CUST_RDXCUST)
       AND CARD.DL_DATA_DT = '${hivevar:snap_dt}'

WHERE TFILE.DL_DATA_DT = '${hivevar:snap_dt}'

  AND CARD.COLL_ID IS NOT NULL
  AND TRIM(CARD.COLL_ID) <> ''
  AND LOWER(TRIM(CARD.COLL_ID)) <> 'null'

  AND CARD.RDXCUST_NO IS NOT NULL
  AND TRIM(CARD.RDXCUST_NO) <> ''
  AND LOWER(TRIM(CARD.RDXCUST_NO)) <> 'null'
